export const getEventBackgroundIcon = (bgIcon?: string, tags?: string[], isColored?: boolean) => {
  if (bgIcon === 'none') return null;

  const colorClass = isColored ? 'text-white opacity-100 dark:text-gray-200 dark:opacity-20' : 'text-[#FD6F2F] opacity-30 dark:text-gray-200 dark:opacity-20';
  const className = `absolute -left-10 top-1/2 -translate-y-1/2 w-48 h-48 -rotate-12 pointer-events-none z-[5] ${colorClass}`;
  
  if (bgIcon && availableIcons[bgIcon]) {
    const IconComponent = availableIcons[bgIcon];
    return <IconComponent className={className} />;
  }

  // Fallback to tags based
  if (!tags) return <Ticket className={className} />;
  const t = tags.join(' ');
  // Sort default background icons by matching tags count
  let bestMatch = 'Ticket';
  let bestScore = 0;
  
  defaultBackgroundIcons.forEach(iconDef => {
    let score = 0;
    iconDef.tags.forEach(tag => {
      if (t.includes(tag)) score++;
    });
    if (score > bestScore) {
      bestScore = score;
      bestMatch = iconDef.icon;
    }
  });

  const IconComponent = availableIcons[bestMatch] || Ticket;
  return <IconComponent className={className} />;
};
